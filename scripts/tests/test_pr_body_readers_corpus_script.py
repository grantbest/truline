@pytest.mark.parametrize("number", _pr_numbers())
def test_merge_pr_sh_stdin_mode_matches_recorded_shell_composition(number):
    """Pins the sh path (via merge-pr.py's --merge-body-from-stdin, which
    merge-pr.sh now calls, AC-4) and the py path to each other and to what
    main's own shell declaration-awk/provenance-grep produced."""
    record = _expected()["records"][str(number)]
    body = _body(number)
    expected = record["merge_pr_sh_declaration"]
    if record["merge_pr_sh_provenance"]:
        expected += "\n" + record["merge_pr_sh_provenance"]

    result = subprocess.run(
        [sys.executable, str(MERGE_PR_PY), "--merge-body-from-stdin"],
        input=body,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.rstrip("\n") == expected


