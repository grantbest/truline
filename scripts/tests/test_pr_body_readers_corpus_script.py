"""AC-7: every PR-body/PR-comment reader must read the 15 real, previously-merged PR bodies and
comments in scripts/tests/fixtures/pr-body-readers/corpus/ EXACTLY as they did on main
(scripts/tests/fixtures/pr-body-readers/corpus/expected.json, generated by the outer loop at
22818b93) -- this bead's fence/line-rule hardening must change what a reader does on a HOSTILE
body (see test_gate_markers.py's hostile-comment fixture test and
apps/factory-dispatcher/tests/test_pr_body_readers_corpus.py / test_dispatch.py's hostile-report
test), never on an ordinary real one.

No `gh`, no network: everything here is a committed fixture.
"""

from __future__ import annotations

import importlib.util
import json
import pathlib
import subprocess
import sys

import pytest


REPO = pathlib.Path(__file__).resolve().parents[2]
FIXTURES = REPO / "scripts" / "tests" / "fixtures" / "pr-body-readers" / "corpus"
MERGE_PR_PY = REPO / "scripts" / "merge-pr.py"


def _load_gate_markers():
    spec = importlib.util.spec_from_file_location("gate_markers_corpus_test", REPO / "scripts" / "gate_markers.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _load_merge_pr():
    spec = importlib.util.spec_from_file_location("merge_pr_corpus_test", MERGE_PR_PY)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _expected():
    return json.loads((FIXTURES / "expected.json").read_text())


def _pr_numbers():
    return sorted(int(n) for n in _expected()["records"].keys())


def _body(number: int) -> str:
    return json.loads((FIXTURES / f"{number}.body.json").read_text())["body"]


def _comment_bodies(number: int) -> list[str]:
    comments = json.loads((FIXTURES / f"{number}.comments.json").read_text())["comments"]
    return [c.get("body") or "" for c in comments]


def test_expected_fixture_has_a_record_for_every_committed_body_file():
    expected = _expected()
    body_files = sorted(p.stem.split(".")[0] for p in FIXTURES.glob("*.body.json"))
    assert sorted(expected["records"].keys(), key=int) == sorted(body_files, key=int)
    assert len(expected["records"]) == 15


@pytest.mark.parametrize("number", _pr_numbers())
def test_merge_pr_py_change_kind_matches_recorded(number):
    merge_pr = _load_merge_pr()
    record = _expected()["records"][str(number)]
    body = _body(number)
    expected_kind = record["merge_pr_py_change_kind"]
    if "declaration" in expected_kind:
        assert merge_pr.extract_change_kind(body) == expected_kind["declaration"]
    else:
        with pytest.raises(merge_pr.Refusal, match=f"found {expected_kind['refusal_count']}"):
            merge_pr.extract_change_kind(body)


